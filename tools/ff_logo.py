"""Flyfish's logo for the FM-1's power-on screen: docs/flyfish-splash.png (docs/flyfish-logo.png without its subtitle) as SIZE x SIZE pixels in the logo's own eight
colours (PALETTE, the nearest for each pixel, no dithering), each row run-length coded (a byte: the run's length - 1
in the high five bits, the colour in the low three), the palette in RGB565, byte-swapped as the screen takes it.
About 6 KB of flash. ff_fw.c (ff_splash) draws it.

  python3 tools/ff_logo.py            write firmware/src/ff_logo.inc
  python3 tools/ff_logo.py --check    1 when it is not up to date"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SIZE = 176
OUT = ROOT / "firmware/src/ff_logo.inc"


def rgb565(c):
    r, g, b = c[:3]
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


# the logo's colours: the background first (the corner), the circle, two blues, the cream, a dark blue, two edges
PALETTE = [(11, 13, 20), (5, 8, 13), (40, 150, 225), (245, 240, 228), (20, 90, 150), (130, 190, 230),
           (160, 165, 170), (70, 120, 160)]


def build():
    im = Image.open(ROOT / "docs/flyfish-splash.png").convert("RGB").resize((SIZE, SIZE), Image.LANCZOS)
    pimg = Image.new("P", (1, 1))
    pimg.putpalette([v for c in PALETTE for v in c] + [0] * (768 - 3 * len(PALETTE)))
    q = im.quantize(palette=pimg, dither=Image.Dither.NONE)
    px = q.load()
    cols = PALETTE
    data, rows = [], []
    for y in range(SIZE):
        rows.append(len(data))
        x = 0
        while x < SIZE:
            c = px[x, y]
            n = 1
            while x + n < SIZE and n < 32 and px[x + n, y] == c:
                n += 1
            data.append((n - 1) << 3 | c)
            x += n
    sw = [((v >> 8) | (v << 8)) & 0xFFFF for v in map(rgb565, cols)]
    text = ["/* SPDX-License-Identifier: GPL-3.0-only */",
            f"/* generated by tools/ff_logo.py from docs/flyfish-splash.png: {SIZE} x {SIZE}, 8 colours, rows run-length",
            f" * coded ({len(data)} bytes); ff_fw.c ff_splash draws it */",
            f"#define FF_LOGO_SIZE {SIZE}",
            f"#define FF_LOGO_BG 0x{rgb565(cols[0]):04X}u              /* the background, as lcd_fill takes it */",
            "static const uint16_t FF_LOGO_PAL[8] = {    /* RGB565, byte-swapped (lcd_blit) */",
            "    " + ", ".join(f"0x{v:04X}" for v in sw) + ",", "};",
            f"static const uint16_t FF_LOGO_ROW[{SIZE}] = {{"]
    for i in range(0, SIZE, 16):
        text.append("    " + ", ".join(str(v) for v in rows[i:i + 16]) + ",")
    text += ["};", f"static const uint8_t FF_LOGO_RLE[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        text.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    text.append("};")
    return "\n".join(text) + "\n", len(data)


def main():
    text, n = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("ff_logo: firmware/src/ff_logo.inc is out of date (python3 tools/ff_logo.py)")
        print(f"ff_logo: {n} bytes, up to date")
        return
    OUT.write_text(text)
    print(f"ff_logo: {SIZE} x {SIZE}, {n} bytes -> {OUT}")


if __name__ == "__main__":
    main()
